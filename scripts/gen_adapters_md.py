#!/usr/bin/env python3
"""Generate ADAPTERS.md, the catalog of keyless-mcp adapters and tools.

    uv run scripts/gen_adapters_md.py            # rewrite ADAPTERS.md
    uv run scripts/gen_adapters_md.py --check    # exit 1 if ADAPTERS.md is out of date (CI)
    make adapters-md                             # same as the first line

The catalog is built from the live registry: ``keyless_mcp.core.discover_adapters`` for each
``adapter.yaml`` and ``keyless_mcp.server.build_server`` for the tool names, so it cannot drift
from the code. Adapters are grouped by toolset. Each row has the adapter, its tools, a link to the
upstream API docs, the author (linked to their GitHub profile) and an agent pass rate column.

Agent pass rates
----------------
Rates come from agent result files, produced by ``scripts/agent_results.py`` from a real
``make agent`` run (the nightly agent job uploads one per harness). By default every
``docs/results/agent-*-latest.json`` is read; pass ``--results FILE [FILE ...]`` to choose files
instead. Each file is one harness and has this schema::

    {
      "harness": "codex",            # column name; one column per distinct harness
      "model": "gpt-6.1-sol",        # shown in the footnote
      "date": "2026-10-11",          # shown in the footnote
      "trials": 1,                   # trials per prompt, shown in the footnote
      "results": {
        "<case id>": {"tool": "arxiv_search", "passed": 1, "total": 1}
      }
    }

``passed``/``total`` are trials of one prompt that picked the right tool. They are summed per
tool, then per adapter, and shown as ``passed/total``. An adapter with no prompts shows a dash.
With no result files the column is a single "Agent pass rate" placeholder.
"""

from __future__ import annotations

import argparse
import difflib
import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from keyless_mcp.core import TOOLSETS, LoadedAdapter  # noqa: E402
from keyless_mcp.server import build_server  # noqa: E402

OUTPUT = ROOT / "ADAPTERS.md"
RESULTS_DIR = ROOT / "docs" / "results"
RESULTS_GLOB = "agent-*-latest.json"
GITHUB = "https://github.com"

TOOLSET_BLURBS = {
    "science": "Research and reference: papers, encyclopedias.",
    "dev": "Developer data: package registries and vulnerability advisories.",
    "geo": "Places and the world: weather, countries.",
    "news": "News and community feeds.",
    "finance": "Money and economic data: exchange rates, public finance, inflation.",
    "reference": "Looking things up: books, holidays, words, entities, web archives.",
    "fun": "Games, trivia and entertainment.",
}

HEADER = """\
# Adapters

<!-- Generated by scripts/gen_adapters_md.py. Do not edit by hand: run `make adapters-md`. -->

Every adapter wraps a free public API that needs no key. Enable a group of them with
`--toolsets` (or `KEYLESS_MCP_TOOLSETS`); the default is all. To add one, see
[docs/adapter-contract.md](docs/adapter-contract.md).
"""


def load_results(paths: list[Path]) -> list[dict]:
    """Read and validate agent result files (schema in the module docstring)."""
    loaded = []
    for path in paths:
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            sys.exit(f"gen_adapters_md: cannot read results file {path}: {exc}")
        try:
            harness = str(data["harness"])
            results = data["results"]
            for case_id, entry in results.items():
                if not (
                    isinstance(entry["tool"], str)
                    and isinstance(entry["passed"], int)
                    and isinstance(entry["total"], int)
                ):
                    raise TypeError(case_id)
        except (KeyError, TypeError, AttributeError) as exc:
            sys.exit(
                f"gen_adapters_md: {path} does not match the results schema "
                f"(harness, results.<case>.tool/passed/total); problem at {exc!r}. "
                "See the docstring of scripts/gen_adapters_md.py."
            )
        loaded.append({**data, "harness": harness, "_path": path})
    return sorted(loaded, key=lambda r: r["harness"])


def tool_totals(result: dict) -> dict[str, tuple[int, int]]:
    """Sum ``(passed, total)`` per tool across the prompts of one result file."""
    totals: dict[str, list[int]] = defaultdict(lambda: [0, 0])
    for entry in result["results"].values():
        totals[entry["tool"]][0] += entry["passed"]
        totals[entry["tool"]][1] += entry["total"]
    return {tool: (p, t) for tool, (p, t) in totals.items()}


def link_author(author: str) -> str:
    handle = author.lstrip("@")
    if handle and all(c.isalnum() or c == "-" for c in handle):
        return f"[{handle}]({GITHUB}/{handle})"
    return author


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render(adapters: list[LoadedAdapter], results: list[dict]) -> str:
    known_tools = {tool for adapter in adapters for tool in adapter.tool_names}
    per_harness = [(r, tool_totals(r)) for r in results]
    for result, totals in per_harness:
        stale = sorted(set(totals) - known_tools)
        if stale:
            print(
                f"gen_adapters_md: warning: {result['_path'].name} mentions tools that no longer "
                f"exist: {', '.join(stale)}",
                file=sys.stderr,
            )

    tool_count = sum(len(a.tool_names) for a in adapters)
    lines = [HEADER, f"**{len(adapters)} adapters, {tool_count} tools.**", ""]
    waiting = [t for t in TOOLSETS if not any(a.spec.toolset == t for a in adapters)]
    if waiting:
        lines += [
            "Toolsets with no adapters yet (they are valid for `--toolsets` and serve no tools "
            f"until the first adapter lands): {', '.join(f'`{t}`' for t in waiting)}.",
            "",
        ]
    pass_headers = [f"Agent pass rate ({r['harness']})" for r in results] or ["Agent pass rate"]

    for toolset in TOOLSETS:
        group = [a for a in adapters if a.spec.toolset == toolset]
        if not group:
            continue
        lines += [f"## {toolset}", "", TOOLSET_BLURBS.get(toolset, ""), ""]
        lines.append("| Adapter | Tools | API docs | Author | " + " | ".join(pass_headers) + " |")
        lines.append("|---|---|---|---|" + "---|" * len(pass_headers))
        for adapter in group:
            spec = adapter.spec
            tools = "<br>".join(f"`{name}`" for name in adapter.tool_names)
            rates = []
            for _result, totals in per_harness:
                pairs = [totals[t] for t in adapter.tool_names if t in totals]
                passed = sum(p for p, _ in pairs)
                rates.append(f"{passed}/{sum(t for _, t in pairs)}" if pairs else "-")
            lines.append(
                f"| **{cell(spec.title)}** (`{spec.name}`)<br>{cell(spec.description)} "
                f"| {tools} | [docs]({spec.docs_url}) | {link_author(spec.author)} "
                f"| {' | '.join(rates or ['-'])} |"
            )
        lines.append("")

    lines.append("## About the agent pass rate")
    lines.append("")
    if results:
        lines.append(
            "Each prompt is a plain-English question that never names a tool; the rate is how "
            "many trials a real agent picked the right tool and called it successfully "
            "(passed/total). A dash means no prompt covers that adapter. One model on one day, "
            "not a stable rate."
        )
        lines.append("")
        for result in results:
            lines.append(
                f"- `{result['harness']}`: model `{result.get('model', 'unknown')}`, "
                f"{result.get('trials', '?')} trial(s) per prompt, "
                f"run on {result.get('date', '?')}."
            )
    else:
        lines.append(
            "Not measured yet. Run `make agent HARNESS=<kind> MODEL=<model>` and "
            "`scripts/agent_results.py` (see [docs/agent-testing.md](docs/agent-testing.md))."
        )
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate ADAPTERS.md from the adapter registry.")
    parser.add_argument(
        "--check", action="store_true", help="do not write; exit 1 if ADAPTERS.md is out of date"
    )
    parser.add_argument(
        "--results",
        nargs="+",
        type=Path,
        metavar="FILE",
        help=f"agent result JSON files (default: docs/results/{RESULTS_GLOB})",
    )
    parser.add_argument("--output", type=Path, default=OUTPUT, help="file to write or check")
    args = parser.parse_args()

    result_paths = args.results if args.results else sorted(RESULTS_DIR.glob(RESULTS_GLOB))
    content = render(build_server().adapters, load_results(result_paths))

    existing = args.output.read_text(encoding="utf-8") if args.output.is_file() else ""
    if args.check:
        if existing == content:
            print(f"{args.output.name} is up to date")
            return 0
        diff = difflib.unified_diff(
            existing.splitlines(),
            content.splitlines(),
            "ADAPTERS.md (committed)",
            "ADAPTERS.md (generated)",
            lineterm="",
        )
        print("\n".join(list(diff)[:40]))
        print(
            f"\n{args.output.name} is out of date. Run `make adapters-md` and commit the result. "
            f"After a merge conflict in {args.output.name}, keep either side first, then run the "
            "same command: it rewrites the whole file.",
            file=sys.stderr,
        )
        return 1
    if existing != content:
        args.output.write_text(content, encoding="utf-8")
        print(f"wrote {args.output}")
    else:
        print(f"{args.output.name} already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
